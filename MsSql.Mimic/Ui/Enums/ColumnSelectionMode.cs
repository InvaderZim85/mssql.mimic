namespace MsSql.Mimic.Ui.Enums;

/// <summary>
/// Specifies the mode used to determine whether columns are included in a selection.
/// </summary>
public enum ColumnSelectionMode
{
    /// <summary>
    /// Indicates that all columns are selected.
    /// </summary>
    All,

    /// <summary>
    /// Indicates that no columns are selected.
    /// </summary>
    None
}